#include "libft.h"

int	ft_tolower(int c)
{
	if ((unsigned char)c == '\0')
	{
		return (0);
	}
	if ((unsigned char)c >= 'A' && (unsigned char)c <= 'Z')
	{
		return (c + 32);
	}
	return (c);
}
