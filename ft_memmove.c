#include "libft.h"

void	*ft_memmove(void *dest, const void *src, size_t n)
{
	size_t			i;
	unsigned char	*s;
	unsigned char	*d;

	s = (unsigned char *)src;
	d = (unsigned char *)dest;
	if (!src && !dest)
	{
		return (0);
	}
	if (n == 0 || (dest == src))
	{
		return (dest);
	}
	if (d > s)
	{
		i = n;
		while (i > 0)
		{
			i--;
			d[i] = s[i];
		}
	}
	else
	{
		i = 0;
		while (i < n) // verificar memcpy
		{
			d[i] = s[i];
			i++;
		}
	}
	return (dest);
}
